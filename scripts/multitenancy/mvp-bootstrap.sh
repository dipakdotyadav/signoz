#!/usr/bin/env bash
set -euo pipefail

# Bootstrap two isolated projects in the organization represented by the
# supplied SigNoz admin token. Project secrets are written once to a 0600 file.

: "${SIGNOZ_API_URL:=http://localhost:8080}"
: "${SIGNOZ_ADMIN_TOKEN:?Set SIGNOZ_ADMIN_TOKEN to an admin bearer token}"
: "${SIGNOZ_MVP_ENV_FILE:=./signoz-mvp-projects.env}"

command -v curl >/dev/null || { echo "curl is required" >&2; exit 1; }
command -v jq >/dev/null || { echo "jq is required" >&2; exit 1; }

api="${SIGNOZ_API_URL%/}"
suffix="$(date -u +%Y%m%d%H%M%S)"
tmp_file="$(mktemp)"
trap 'rm -f "$tmp_file"' EXIT
umask 077

post_json() {
  local path="$1"
  local payload="$2"
  curl --fail-with-body --silent --show-error \
    -X POST "${api}${path}" \
    -H "Authorization: Bearer ${SIGNOZ_ADMIN_TOKEN}" \
    -H "Content-Type: application/json" \
    --data "$payload"
}

create_project() {
  local label="$1"
  local slug="$2"
  local response
  response="$(post_json "/api/v2/projects" "$(jq -n \
    --arg name "MVP ${label} ${suffix}" \
    --arg slug "${slug}-${suffix}" \
    --arg description "Temporary multi-tenancy MVP validation project" \
    '{name:$name,slug:$slug,description:$description}')")"
  jq -er '.data.id' <<<"$response"
}

create_key() {
  local project_id="$1"
  local label="$2"
  local response
  response="$(post_json "/api/v2/projects/${project_id}/ingestion-keys" \
    "$(jq -n --arg name "mvp-${label}-${suffix}" '{name:$name}')")"
  jq -er '.data.secret' <<<"$response"
}

echo "Creating Project A..."
project_a_id="$(create_project "Tenant A" "mvp-tenant-a")"
echo "Creating Project B..."
project_b_id="$(create_project "Tenant B" "mvp-tenant-b")"

echo "Creating project-scoped ingestion credentials..."
project_a_key="$(create_key "$project_a_id" "tenant-a")"
project_b_key="$(create_key "$project_b_id" "tenant-b")"

cat >"$tmp_file" <<EOF
# Generated by scripts/multitenancy/mvp-bootstrap.sh
# Treat this file as a secret. The ingestion keys are shown only once.
SIGNOZ_API_URL='$api'
PROJECT_A_ID='$project_a_id'
PROJECT_B_ID='$project_b_id'
PROJECT_A_KEY='$project_a_key'
PROJECT_B_KEY='$project_b_key'
EOF

install -m 600 "$tmp_file" "$SIGNOZ_MVP_ENV_FILE"
echo "Bootstrap complete."
echo "Project IDs and one-time secrets saved to: $SIGNOZ_MVP_ENV_FILE"
echo "Protect this file; do not commit it or paste its contents into logs/issues."
